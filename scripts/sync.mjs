#!/usr/bin/env node
// Regenerates the reference section (API, data model, plans, portal routes)
// from the master branch of the three NextCybr repos.
//
// Everything is read with `git show master:<path>` / `git ls-tree master`, so
// the output always reflects master no matter which branch each repo has
// checked out locally. Hand-written guides under docs/ are never touched;
// only docs/reference/** and src/data/sync.json are overwritten.
//
// Usage:  npm run sync            (repos expected next to this project)
//         REPOS_DIR=/path npm run sync
//         SYNC_REF=origin/master npm run sync

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const DOCS_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const REPOS_DIR = process.env.REPOS_DIR || path.resolve(DOCS_ROOT, "..");
const REF = process.env.SYNC_REF || "master";
const REPOS = {
  server: path.join(REPOS_DIR, "nextcybr-server"),
  portal: path.join(REPOS_DIR, "nextcybr-portal"),
  admin: path.join(REPOS_DIR, "nextcybr-admin-portal"),
};
const OUT = path.join(DOCS_ROOT, "docs", "reference");

// ─── git helpers ────────────────────────────────────────────────────────────

const git = (repo, args) =>
  execFileSync("git", ["-C", repo, ...args], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
const show = (repo, file) => git(repo, ["show", `${REF}:${file}`]);
const lsTree = (repo, dir) =>
  git(repo, ["ls-tree", "-r", "--name-only", REF, "--", dir]).split("\n").filter(Boolean);
const headInfo = (repo) => {
  const [sha, date, subject] = git(repo, ["log", "-1", "--format=%h%x09%cI%x09%s", REF])
    .trim()
    .split("\t");
  return { sha, date, subject };
};

// ─── output helpers ─────────────────────────────────────────────────────────

const write = (rel, content) => {
  const file = path.join(OUT, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
};
const esc = (s) =>
  String(s ?? "")
    .replace(/\|/g, "\\|")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/\{/g, "&#123;")
    .replace(/\}/g, "&#125;");
const code = (s) => "`" + String(s).replace(/`/g, "'") + "`";
const humanize = (name) => {
  const words = name
    .replace(/^admin(?=[A-Z])/, "admin ")
    .replace(/Handler$/, "")
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1 $2")
    .toLowerCase()
    .split(/\s+/);
  const s = words.join(" ");
  return s.charAt(0).toUpperCase() + s.slice(1);
};
const banner = (repos) =>
  `:::info[Generated page]\n\nThis page is generated by \`npm run sync\` from \`${REF}\` of ${repos
    .map((r) => `**${r}**`)
    .join(", ")}. Do not edit it by hand — changes are overwritten on the next sync.\n:::\n`;

