// ─── 3. Plans & feature matrix ──────────────────────────────────────────────

function extractArray(src, name) {
  const start = src.indexOf(`const ${name} = [`);
  if (start < 0) throw new Error(`sync: ${name} not found in seedEntitlementSystem.js`);
  let depth = 0;
  let i = src.indexOf("[", start);
  const from = i;
  for (; i < src.length; i++) {
    if (src[i] === "[") depth++;
    else if (src[i] === "]" && --depth === 0) break;
  }
  // Data-only literal from our own repo (strings, numbers, objects).
  return new Function(`return ${src.slice(from, i + 1)};`)();
}

function generatePlans() {
  const src = show(REPOS.server, "prisma/seedEntitlementSystem.js");
  const plans = extractArray(src, "PLANS");
  const features = extractArray(src, "FEATURES");
  const values = extractArray(src, "VALUES");
  const retired = (() => {
    try { return extractArray(src, "RETIRED_FEATURE_KEYS"); } catch { return []; }
  })();
  const live = features.filter((f) => !retired.includes(f.key));
  // Seeded but with no product behind them yet; the admin matrix locks these.
  const unbuilt = (() => {
    try { return extractArray(show(REPOS.server, "src/constants/unbuiltFeatures.js"), "UNBUILT_FEATURE_KEYS"); } catch { return []; }
  })();
  const notBuilt = (key) => (unbuilt.includes(key) ? ` <span class="gate gate--quota" title="No product behind it yet. Don't sell it.">Not built</span>` : "");

  const val = (userType, planKey, featureKey) => {
    const v = values.find((x) => x[0] === userType && x[1] === planKey && x[2] === featureKey);
    if (!v) return "<span class=\"cell-unset\">unset</span>";
    const o = v[3];
    if (o.enabled === false) return "<span class=\"cell-no\">✕</span>";
    if (o.isUnlimited) return "<span class=\"cell-yes\">Unlimited</span>";
    if (o.limitValue !== undefined && o.limitValue !== null) return `<strong>${Number(o.limitValue).toLocaleString("en-US")}</strong>`;
    return "<span class=\"cell-yes\">✓</span>";
  };
  const RESET = { NONE: "Capacity", DAILY: "Daily", THIRTY_DAY_ROLLING: "Rolling 30 days", SEVEN_DAY_ROLLING: "Rolling 7 days", MONTHLY_CALENDAR: "Calendar month", BILLING_CYCLE: "Billing cycle" };
  const LABEL = { STUDENT: "Candidate (STUDENT)", COMPANY: "Recruiter (COMPANY)", MENTOR: "Mentor (MENTOR)" };

  const sections = ["STUDENT", "COMPANY", "MENTOR"].map((ut) => {
    const tiers = plans.filter((p) => p.userType === ut).sort((a, b) => a.tierRank - b.tierRank);
    const tierRows = tiers
      .map((p) => `| **${p.name}** | ${code(p.key)} | ${p.price ? `$${p.price}/mo` : p.key === "FREE" ? "Free" : "Custom"} | ${esc(p.description)} | ${p.stripeMonthlyEnv ? code(p.stripeMonthlyEnv) + "<br/>" + code(p.stripeYearlyEnv) : "—"} |`)
      .join("\n");
    const feats = live.filter((f) => f.appliesTo === ut || f.appliesTo === "ALL" || (Array.isArray(f.appliesTo) && f.appliesTo.includes(ut)));
    const cats = [...new Set(feats.map((f) => f.category))];
    const matrix = cats
      .map((cat) => {
        const rows = feats
          .filter((f) => f.category === cat)
          .map((f) => `| <span title="${esc(f.description)}">${esc(f.name)}</span>${notBuilt(f.key)}<br/><code>${f.key}</code> | ${f.type === "BOOLEAN" ? "On/off" : RESET[f.resetPeriod] || f.resetPeriod} | ${tiers.map((p) => val(ut, p.key, f.key)).join(" | ")} |`)
          .join("\n");
        return `#### ${cat}\n\n| Feature | Type | ${tiers.map((p) => p.name.replace(/^(Candidate|Mentor|Recruiter) /, "")).join(" | ")} |\n| --- | --- | ${tiers.map(() => "---").join(" | ")} |\n${rows}`;
      })
      .join("\n\n");
    return `## ${LABEL[ut]}\n\n### Tiers\n\n| Plan | Key | List price | Positioning | Stripe price env vars |\n| --- | --- | --- | --- | --- |\n${tierRows}\n\n### Feature matrix\n\n${matrix}\n`;
  });

  write(
    "plans.mdx",
    `---\ntitle: Plans & feature matrix\nsidebar_position: 3\ndescription: Seeded plan tiers and every feature limit per tier.\n---\n\n# Plans & feature matrix\n\n${banner(["nextcybr-server"])}\nThese are the **seeded defaults** from \`prisma/seedEntitlementSystem.js\`. Admins can change any value at runtime from **Admin portal → Entitlements**, and add per-country prices, so production may differ. The live values are always in the \`PlanFeatureValue\` table.\n\n- **${plans.length} plans** across three audiences · **${live.length} feature definitions**\n- <strong>Number</strong> = limit per period · <span class="cell-yes">Unlimited</span> · <span class="cell-yes">✓</span> enabled · <span class="cell-no">✕</span> disabled · <span class="cell-unset">unset</span> = no seeded value (the engine treats a missing row as disabled)\n- <span class="gate gate--quota">Not built</span> = seeded but no product behind it yet (\`src/constants/unbuiltFeatures.js\`). The admin matrix locks these; don't sell them.\n- **Type** — \`Capacity\` limits count live records (e.g. active services); the others are counters that reset on the given schedule.\n\nHow these resolve at request time is covered in [Plans & entitlements engine](/backend/entitlements).\n\n${sections.join("\n")}`,
  );
  return { plans: plans.length, features: live.length };
}

// ─── 4. Portal & admin route maps ───────────────────────────────────────────

function generateRouteMaps() {
  const files = lsTree(REPOS.portal, "app").filter((f) => /\/page\.jsx?$/.test(f));
  const routeAccess = show(REPOS.portal, "constants/routeAccess.js");
  const groupOf = (f) => (f.includes("(protected)") ? "Signed-in app" : f.includes("(static)") ? "Public site" : f.includes("onboarding") ? "Onboarding" : "Public site");
  const toRoute = (f) => f.replace(/^app/, "").replace(/\/\([^)]+\)/g, "").replace(/\/page\.jsx?$/, "") || "/";
  const groups = {};
  for (const f of files) (groups[groupOf(f)] ||= []).push({ route: toRoute(f), file: f });

  const sidebar = show(REPOS.portal, "components/navigation/SideBar.js");
  const menus = {};
  for (const role of ["STUDENT", "COMPANY", "MENTOR"]) menus[role] = [];
  // The sidebar is three arrays in STUDENT → COMPANY → MENTOR order.
  const chunks = sidebar.split(/user\?\.role === "(?:STUDENT|COMPANY)"/);
  const roleOrder = ["STUDENT", "COMPANY", "MENTOR"];
  chunks.slice(1).forEach((chunk, idx) => {
    const parts = idx === 1 ? chunk.split(/\]\s*:\s*\[/) : [chunk];
    parts.forEach((part, j) => {
      const role = roleOrder[idx + j];
      if (!role) return;
      const live = part.split("\n").filter((l) => !/^\s*\/\//.test(l)).join("\n");
      for (const m of live.matchAll(/label:\s*"([^"]+)"[\s\S]*?href:\s*"([^"]+)"/g)) {
        if (!menus[role].some((x) => x.href === m[2])) menus[role].push({ label: m[1], href: m[2] });
      }
    });
  });
  const menuTable = roleOrder
    .map((r) => `### ${r}\n\n| Menu item | Route |\n| --- | --- |\n${menus[r].map((m) => `| ${m.label} | ${code(m.href)} |`).join("\n")}\n`)
    .join("\n");

  const routeTables = ["Public site", "Onboarding", "Signed-in app"]
    .filter((g) => groups[g])
    .map((g) => `## ${g}\n\n| Route | Source file |\n| --- | --- |\n${groups[g].sort((a, b) => a.route.localeCompare(b.route)).map((r) => `| ${code(r.route)} | ${code(r.file)} |`).join("\n")}\n`)
    .join("\n");

  const app = show(REPOS.admin, "src/App.jsx");
  const adminRoutes = [];
  for (const m of app.matchAll(/<Route\s+path="([^"]+)"[\s\S]*?element=\{\s*(?:<\w+[^>]*>\s*)?<(\w+)/g)) {
    adminRoutes.push({ path: m[1].startsWith("/") ? m[1] : `/${m[1]}`, el: m[2] });
  }

  write(
    "frontend-routes.mdx",
    `---\ntitle: Frontend route maps\nsidebar_position: 4\ndescription: Every page route in the portal and admin portal.\n---\n\n# Frontend route maps\n\n${banner(["nextcybr-portal", "nextcybr-admin-portal"])}\n## Portal (Next.js App Router)\n\nRoute groups \`(static)\` and \`(protected)\` don't appear in URLs. The Edge \`middleware.js\` redirects signed-out visitors away from anything not listed in \`constants/routeAccess.js\` (public paths) to \`/auth/sign-in?returnUrl=…\`, and bounces signed-in users away from the auth pages to \`/dashboard\`.\n\n### Sidebar menu by role\n\nFrom \`components/navigation/SideBar.js\`.\n\n${menuTable}\n${routeTables}\n<details>\n<summary>Public path rules (<code>constants/routeAccess.js</code>)</summary>\n\n\`\`\`js\n${routeAccess.trim()}\n\`\`\`\n\n</details>\n\n## Admin portal (React Router)\n\nAll routes except \`/signin\` render inside the authenticated layout guarded by \`PrivateRoute\`. Unknown paths redirect to \`/signin\`.\n\n| Path | Screen component |\n| --- | --- |\n${adminRoutes.map((r) => `| ${code(r.path)} | ${code(r.el)} |`).join("\n")}\n`,
  );
  return { portal: files.length, admin: adminRoutes.length };
}

